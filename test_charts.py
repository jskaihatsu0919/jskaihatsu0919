ok = fail = 0


def chk(label, got, exp):
    global ok, fail
    if got == exp:
        ok += 1
    else:
        fail += 1
        print(f"    ✗ {label}: 算出={got} / 帳票={exp}")


for c in CASES:
    r = build(c["name"], c["y"], c["m"], c["d"], c["male"])
    print(f"\n=== {c['name']} {c['y']}/{c['m']}/{c['d']} ===")
    print(f"    節入 {r.meta['節入']} / 経過 {r.meta['経過日数']}日 / "
          f"{'順行' if r.meta['順行'] else '逆行'} / 立運{r.meta['立運']}")
    for k in ("年", "月", "日"):
        chk(f"{k}柱", r.pillars[k], c["pillars"][k])
    chk("干支番号", r.pillars["番号"], c["nums"])
    for k, v in c["jinzu"].items():
        chk(k, r.jinzu[k], v)
    for k, v in c["jyusei"].items():
        chk(k, r.jyusei[k], v)
    for k, v in c["cross"].items():
        chk(f"五行{k}", r.gogyo[k], v)
    chk("立運", r.meta["立運"], c["ritsuun"])
    chk("天中殺(日)", r.meta["天中殺_日"], c["tcs"][0])
    chk("天中殺(年)", r.meta["天中殺_年"], c["tcs"][1])
    if "shugo" in c:
        chk("守護神", r.meta["守護神"], c["shugo"])
    chk("大運干支", [d["kanshi"] for d in r.daiun], c["daiun"])
    chk("大運年齢", [d["age"] for d in r.daiun],
        [c["ritsuun"] + i * 10 for i in range(10)])
    chk("気", [d["気"] for d in r.daiun], c["ki"])

print(f"\n{'='*46}\n一致 {ok} 件 / 不一致 {fail} 件")
